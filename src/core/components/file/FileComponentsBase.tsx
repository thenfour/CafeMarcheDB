import * as db3 from "src/core/db3/db3";
import * as DB3Client from "src/core/db3/DB3Client";

export const FileTableClientColumns = DB3Client.makeClientColumnSet({
    publicId: DB3Client.publicIdFieldGen(),
    fileLeafName: columnName => new DB3Client.GenericStringColumnClient({ fieldDescriptionKey: null, columnName, cellWidth: 200, fieldCaptionKey: "db3.fields.fileName", className: "titleText" }),
    storedLeafName: columnName => new DB3Client.GenericStringColumnClient({ fieldDescriptionKey: null, columnName, cellWidth: 150, fieldCaptionKey: "db3.fields.storedFileName" }),
    description: columnName => new DB3Client.MarkdownStringColumnClient({ fieldDescriptionKey: null, fieldCaptionKey: "db3.fields.description", columnName, cellWidth: 200 }),
    uploadedAt: columnName => new DB3Client.CreatedAtColumn({ fieldDescriptionKey: null, fieldCaptionKey: "db3.fields.uploadedAt", columnName, cellWidth: 150 }),
    uploadedByUser: columnName => new DB3Client.ForeignSingleFieldClient({ fieldDescriptionKey: null, fieldCaptionKey: "db3.fields.uploadedBy", columnName, cellWidth: 120 }),
    sizeBytes: columnName => new DB3Client.GenericIntegerColumnClient({ fieldDescriptionKey: null, fieldCaptionKey: "db3.fields.fileSize", columnName, cellWidth: 80 }),
    mimeType: columnName => new DB3Client.GenericStringColumnClient({ fieldDescriptionKey: null, fieldCaptionKey: "db3.fields.mimeType", columnName, cellWidth: 120 }),
    visiblePermission: DB3Client.foreignRefFieldGen({ fieldDescriptionKey: "File.visiblePermission.DescriptionMarkdown", fieldCaptionKey: "db3.fields.visibility",
        selectionView: db3.permissionVisibilityView,
    }),

    tags: columnName => new DB3Client.TagsFieldClient<db3.FileEditorTag>({
        columnName,
        cellWidth: 150,
        fieldCaptionKey: "db3.fields.tags",
        fieldDescriptionKey: null,
        selectStyle: "inline",
        allowDeleteFromCell: false,
        selectionView: db3.bandFileTagView,
    }),
    taggedUsers: columnName => new DB3Client.TagsFieldClient<db3.FileEditorUserTag>({
        selectionView: db3.bandUserIdentityView,
        columnName,
        cellWidth: 150,
        fieldCaptionKey: "db3.fields.members",
        fieldDescriptionKey: null,
        selectStyle: "inline",
        allowDeleteFromCell: false,
    }),
    taggedSongs: columnName => new DB3Client.TagsFieldClient<db3.FileEditorSongTag>({ selectionView: db3.songReferenceView, selectStyle: "inline", fieldDescriptionKey: null, fieldCaptionKey: "db3.fields.songs", columnName, cellWidth: 150, allowDeleteFromCell: false }),
    taggedEvents: columnName => new DB3Client.TagsFieldClient<db3.FileEditorEventTag>({
        selectionView: db3.eventReferenceView,
        columnName,
        cellWidth: 150,
        fieldCaptionKey: "db3.fields.events",
        fieldDescriptionKey: null,
        selectStyle: "inline",
        allowDeleteFromCell: false,
    }),
    taggedInstruments: columnName => new DB3Client.TagsFieldClient<db3.FileEditorInstrumentTag>({
        selectionView: db3.instrumentDashboardView,
        columnName,
        cellWidth: 150,
        fieldCaptionKey: "db3.fields.instruments",
        fieldDescriptionKey: null,
        selectStyle: "inline",
        allowDeleteFromCell: false,
    }),
    taggedWikiPages: columnName => new DB3Client.TagsFieldClient<db3.FileEditorWikiPageTag>({
        columnName,
        cellWidth: 150,
        fieldCaptionKey: "db3.fields.wikiPages",
        fieldDescriptionKey: null,
        selectStyle: "inline",
        allowDeleteFromCell: false,
    }),
    previewFile: columnName => new DB3Client.ForeignSingleFieldClient({ fieldDescriptionKey: null, fieldCaptionKey: "db3.fields.previewFile", columnName, cellWidth: 120 }),
    parentFile: columnName => new DB3Client.ForeignSingleFieldClient({ fieldDescriptionKey: null, fieldCaptionKey: "db3.fields.parentFile", columnName, cellWidth: 120 }),
    externalURI: columnName => new DB3Client.GenericStringColumnClient({ fieldDescriptionKey: null, fieldCaptionKey: "db3.fields.externalUrl", columnName, cellWidth: 200 }),
    customData: columnName => new DB3Client.GenericStringColumnClient({ fieldDescriptionKey: null, fieldCaptionKey: "db3.fields.customData", columnName, cellWidth: 150 }),
    fileCreatedAt: columnName => new DB3Client.DateTimeColumn({ fieldDescriptionKey: null, fieldCaptionKey: "db3.fields.fileCreatedAt", columnName }),
    isDeleted: columnName => new DB3Client.BoolColumnClient({ fieldDescriptionKey: null, fieldCaptionKey: "db3.fields.deleted", columnName }),
});
